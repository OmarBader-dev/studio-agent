def tz_for(state):
    return STATE_TZ.get((state or "").upper(), "America/New_York")


def local_now(state):
    return dt.datetime.now(ZoneInfo(tz_for(state)))


def in_send_window(state, hours):
    """True on weekdays between hours[0] and hours[1] in the business's own time zone."""
    t = local_now(state)
    return t.weekday() < 5 and hours[0] <= t.hour < hours[1]
